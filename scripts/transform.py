#!/usr/bin/env python3
"""Convert the upstream Mintlify .mdx spec sources (source/1.0/) into
translatable mkdocs input (docs-zh/1.0/).

Deterministic and idempotent; does NOT translate — translation is the
model's job. Per file it:
  * keeps YAML frontmatter (title/description — the translator localizes them)
  * rewrites absolute /spec/1.0/... links to repo-relative .md paths (so
    `mkdocs build --strict` verifies every internal link)
  * rewrites /spec/1.0/schema.json -> the in-repo copy of the schema
  * converts Mintlify <CardGroup>/<Card> to a markdown list
  * converts Mintlify <Note> to a neutral callout (styled later in CSS)
  * injects explicit English {#slug} anchors into every heading so the many
    cross-page #anchor links (copied verbatim from the upstream prose) resolve
    exactly as they do on the original Mintlify site.

schema.mdx is intentionally skipped: it is generated upstream from
schema.json and its Chinese version is generated by scripts/gen_schema.py.

Usage:  python3 scripts/transform.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "source")
OUT = os.path.join(ROOT, "docs-zh")
SPEC_PREFIX = "/spec/1.0/"


def file_depth(rel_path):
    """`../` count from the file's dir to the spec root (source/1.0/)."""
    return rel_path.split("/").__len__() - 2  # minus '1.0' and the filename


def spec_rel_to_md(spec_path, up):
    if spec_path == "/spec/1.0":
        return f"{up}index.md"
    p = spec_path[len(SPEC_PREFIX):] if spec_path.startswith(SPEC_PREFIX) else spec_path
    if p.endswith(".json"):
        return f"{up}schema.json"
    p = p.rstrip("/")
    if p in ("", ".md"):
        return f"{up}index.md"
    if p.endswith("/index"):
        p = p[: -len("/index")]
    # a Mintlify page that is a directory (e.g. /spec/1.0/basic) is an
    # index page in the repo: link to basic/index.md, not basic.md
    if os.path.isdir(os.path.join(SRC, "1.0", p)):
        p = f"{p}/index"
    return f"{up}{p}.md"


def resolve_link(target, rel_path):
    up = "../" * file_depth(rel_path)
    if target.startswith("#CARDHREF#"):
        return resolve_link(target[len("#CARDHREF#"):], rel_path)
    if target == "/spec/1.0" or target.startswith(SPEC_PREFIX):
        path, _, anchor = target.partition("#")
        return f"]({spec_rel_to_md(path, up)}{('#' + anchor) if anchor else ''})"
    if target.startswith("/") and not target.startswith("//"):
        # a page outside the spec section: point at the live original site
        return f"](https://docs.ag-ui.com{target})"
    return f"]({target})"


def slugify(text):
    s = re.sub(r"\s+", " ", text).strip().lower()
    s = re.sub(r"[^a-z0-9 ]", "", s)
    return s.replace(" ", "-")


def rewrite_headings(lines):
    out = []
    for ln in lines:
        m = re.match(r"^(#{1,6})\s+(.*)$", ln)
        if m and "{#" not in ln:
            text = m.group(2).strip()
            cm = re.match(r"^`([^`]+)`\s*$", text)
            slug = slugify(cm.group(1) if cm else text)
            if slug:
                out.append(f"{m.group(1)} {text} {{#{slug}}}")
                continue
        out.append(ln)
    return out


def convert_cards(md):
    def group_repl(m):
        cards = re.findall(
            r'<Card\s+title="([^"]*)"(?:\s+icon="[^"]*")?\s+href="([^"]*)"[^>]*>\s*(.*?)\s*</Card>',
            m.group(1),
            re.DOTALL,
        )
        if not cards:
            return m.group(0)
        items = []
        for title, href, desc in cards:
            href = href.strip()
            link = (
                f"[{title}](#CARDHREF#{href})"
                if href.startswith(SPEC_PREFIX)
                else f"[{title}]({href})"
            )
            items.append(f"- {link} — {' '.join(desc.split())}")
        return "\n".join(items) + "\n"

    md = re.sub(r"<CardGroup[^>]*>(.*?)</CardGroup>", group_repl, md, flags=re.DOTALL)
    md = re.sub(
        r'<Card\s+title="([^"]*)"(?:\s+icon="[^"]*")?\s+href="([^"]*)"[^>]*>\s*(.*?)\s*</Card>',
        lambda m: f"- [{m.group(1)}](#CARDHREF#{m.group(2).strip()}) — {' '.join(m.group(3).split())}\n",
        md,
        flags=re.DOTALL,
    )
    return md


def convert_notes(md):
    # python-markdown admonition：!!! type 开头 + 正文缩进 4 格，无闭合行
    def repl(m):
        body = "\n".join("    " + ln for ln in m.group(1).strip().splitlines())
        return "!!! note\n" + body + "\n"

    return re.sub(r"<Note>\s*\n(.*?)\n\s*</Note>", repl, md, flags=re.DOTALL)


def process(rel_path):
    src_path = os.path.join(SRC, rel_path)
    out_path = os.path.join(OUT, rel_path.replace(".mdx", ".md"))
    with open(src_path, encoding="utf-8") as f:
        text = f.read()

    fm_m = re.match(r"^---\n(.*?)\n---\n", text, re.DOTALL)
    frontmatter = fm_m.group(0) if fm_m else ""
    body = text[fm_m.end():] if fm_m else text

    body = convert_cards(body)
    body = convert_notes(body)
    body = re.sub(
        r"\]\((?:#CARDHREF#)?(/[a-zA-Z][^)]*)\)",
        lambda m: resolve_link(m.group(1), rel_path),
        body,
    )
    body = "\n".join(rewrite_headings(body.splitlines()))
    body = re.sub(r"\n{3,}", "\n\n", body).strip() + "\n"

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(frontmatter + body)


def main():
    count = 0
    for dirpath, _d, files in os.walk(SRC):
        for fn in sorted(files):
            if not fn.endswith(".mdx"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, fn), SRC).replace(os.sep, "/")
            if rel.endswith("schema.mdx"):
                continue  # generated page, translated separately
            process(rel)
            count += 1
    print(f"converted {count} files -> docs-zh/")


if __name__ == "__main__":
    main()
